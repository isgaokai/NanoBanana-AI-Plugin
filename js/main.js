    function t(key) {
        return translations[config.language][key] || key;
    }

    function updateTranslations() {
        try {
            // Update all elements with data-i18n attribute
            const elements = document.querySelectorAll('[data-i18n]');
            console.log(`Updating ${elements.length} elements with translations`);
            
            elements.forEach((el, index) => {
                if (!el) {
                    console.warn(`Element ${index} is null`);
                    return;
                }
                
                const key = el.getAttribute('data-i18n');
                if (!key) {
                    console.warn(`Element ${index} has no data-i18n key`);
                    return;
                }
                
                const translation = t(key);
                if (!translation) {
                    console.warn(`No translation found for key: ${key}`);
                    return;
                }
                
                try {
                    // 对于包含子元素的元素（如按钮内有 SVG + 文本），使用特殊处理
                    const hasChildElements = el.children.length > 0;
                    const isSimpleSpan = el.children.length === 1 && el.children[0]?.tagName === 'SPAN';
                    
                    if (!hasChildElements || isSimpleSpan) {
                        // 简单元素，直接替换
                        el.textContent = translation;
                    } else {
                        // 复杂元素，只更新纯文本节点
                        let updated = false;
                        for (let node of el.childNodes) {
                            if (node.nodeType === Node.TEXT_NODE && node.textContent.trim()) {
                                node.textContent = translation;
                                updated = true;
                                break;
                            }
                        }
                        if (!updated) {
                            console.warn(`Could not update text for element with key: ${key}`);
                        }
                    }
                } catch (error) {
                    console.error(`Translation update failed for key "${key}":`, error, el);
                    customAlert('错误: ' + error.message);  // 显示详细错误
                }
            });

            // Update placeholders
            document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
                if (!el) return;
                const key = el.getAttribute('data-i18n-placeholder');
                if (!key) return;
                try {
                    const translation = t(key);
                    if (translation) {
                        el.placeholder = translation;
                    }
                } catch (error) {
                    console.error('Placeholder update failed:', error);
                }
            });

            // Update titles
            document.querySelectorAll('[data-i18n-title]').forEach(el => {
                if (!el) return;
                const key = el.getAttribute('data-i18n-title');
                if (!key) return;
                try {
                    const translation = t(key);
                    if (translation) {
                        el.title = translation;
                    }
                } catch (error) {
                    console.error('Title update failed:', error);
                }
            });
            
            console.log('Translation update completed');
        } catch (error) {
            console.error('Fatal error in updateTranslations:', error);
            customAlert('翻译更新失败: ' + error.message);
        }
    }

