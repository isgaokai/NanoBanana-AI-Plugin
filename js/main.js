    // ========== File to Base64 ==========
    async function fileToBase64(filePath) {
        return new Promise((resolve, reject) => {
            try {
                logDebug('info', 'Reading File', { filePath: filePath });
                
                // Use CSInterface file system
                const fs = window.cep.fs;
                
                // Read file as Base64 directly (avoid binary encoding issues)
                const result = fs.readFile(filePath, cep.encoding.Base64);
                
                if (result.err !== 0) {
                    logDebug('error', 'File Read Error', { err: result.err });
                    reject(new Error('Failed to read file: ' + result.err));
                    return;
                }
                
                // CEP fs.readFile with Base64 encoding returns pure base64 string
                const base64 = result.data;
                const dataUrl = 'data:image/jpeg;base64,' + base64;
                
                logDebug('info', 'File Converted to Base64', { 
                    length: base64.length,
                    preview: dataUrl.substring(0, 100) + '...'
                });
                
                resolve(dataUrl);
            } catch (error) {
                logDebug('error', 'Base64 Conversion Error', error.message);
                reject(error);
            }
        });
    }

